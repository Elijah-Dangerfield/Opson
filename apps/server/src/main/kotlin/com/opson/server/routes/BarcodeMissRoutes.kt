package com.opson.server.routes

import com.opson.server.domain.BarcodeLookup
import com.opson.server.domain.BarcodeMiss
import com.opson.server.domain.BarcodeMissRepository
import com.opson.server.http.ClientContext
import com.opson.server.http.clientContext
import com.opson.server.plugins.BARCODE_MISS_LIMIT
import com.opson.server.plugins.SUPABASE_JWT_AUTH
import com.opson.server.plugins.problem
import io.ktor.http.HttpStatusCode
import io.ktor.server.auth.authenticate
import io.ktor.server.plugins.ratelimit.RateLimitName
import io.ktor.server.plugins.ratelimit.rateLimit
import io.ktor.server.request.receive
import io.ktor.server.response.respond
import io.ktor.server.routing.Route
import io.ktor.server.routing.post
import kotlinx.serialization.Serializable
import java.util.UUID

/** `POST /v1/foods/barcode-misses`. [id] is generated by the app, so a retry is the same miss. */
@Serializable
data class BarcodeMissRequest(val id: String? = null, val barcode: String? = null)

/**
 * The app reports a barcode that `GET /v1/foods/barcode/{code}` answered 404.
 * 204 on success and on a repeat of the same id. 400 `invalid_id` or
 * `invalid_barcode`. Region, platform and app version come from the headers
 * every client already sends; the caller's id is required (JWT) but never
 * stored. Added in 0.2; 0.1 never calls it.
 */
fun Route.barcodeMissRoutes(misses: BarcodeMissRepository) {
    authenticate(SUPABASE_JWT_AUTH) {
        rateLimit(RateLimitName(BARCODE_MISS_LIMIT)) {
            post("/v1/foods/barcode-misses") {
                val request = call.receive<BarcodeMissRequest>()
                val id = request.id?.let { runCatching { UUID.fromString(it) }.getOrNull() }
                    ?: return@post call.respond(HttpStatusCode.BadRequest, problem("invalid_id", "id must be a UUID"))
                val code = request.barcode?.trim().orEmpty()
                if (!BarcodeLookup.isValidBarcode(code)) {
                    return@post call.respond(
                        HttpStatusCode.BadRequest,
                        problem("invalid_barcode", "A barcode is 8 to 14 digits"),
                    )
                }
                val client = call.clientContext()
                misses.record(
                    BarcodeMiss.of(
                        id = id,
                        barcode = code,
                        country = client.countryCode,
                        platform = client.platform.wire,
                        appVersion = client.appVersion,
                    ),
                )
                call.respond(HttpStatusCode.NoContent)
            }
        }
    }
}

private val ClientContext.Platform.wire: String
    get() = when (this) {
        ClientContext.Platform.Android -> "android"
        ClientContext.Platform.iOS -> "ios"
        ClientContext.Platform.Other -> "other"
    }
