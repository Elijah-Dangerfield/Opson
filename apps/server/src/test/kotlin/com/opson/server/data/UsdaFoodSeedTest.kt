import kotlinx.coroutines.test.runTest
import org.jetbrains.exposed.sql.selectAll
import org.jetbrains.exposed.sql.transactions.TransactionManager
import org.junit.After
import org.junit.Assume
import java.io.File
import java.util.zip.GZIPInputStream
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue
import kotlin.time.Clock

/**
 * Applies the committed USDA seed (`fooddb/usda_foods.sql.gz`, generated by
 * scripts/import_usda_foods.py) to a freshly migrated Postgres. Proves the
 * file matches the V7 schema, that applying it twice is a no-op, and that the
 * foods people log most come back from search looking right.
 */
class UsdaFoodSeedTest : DatabaseTest() {

    @After
    fun clean() = DiaryFixtures.cleanAll(database)

    private val seed = File("fooddb/usda_foods.sql.gz")

    private fun apply() {
        val sql = GZIPInputStream(seed.inputStream()).bufferedReader().use { it.readText() }
        database.blockingTransaction {
            val jdbc = TransactionManager.current().connection.connection as java.sql.Connection
            jdbc.createStatement().use { it.execute(sql) }
        }
    }

    private fun count(): Long = database.blockingTransaction { FoodsTable.selectAll().count() }

    @Test
    fun seedAppliesIdempotentlyAndSearchesWell() = runTest {
        Assume.assumeTrue("USDA seed not generated", seed.exists())
        apply()
        val first = count()
        apply()
        assertEquals(first, count(), "re-applying the seed must update in place")
        assertTrue(first > 12_000, "expected the full USDA catalog, got $first")

        val sources = database.blockingTransaction {
            FoodsTable.selectAll().map { it[FoodsTable.sourceKind] }.groupingBy { it }.eachCount()
        }
        assertEquals(setOf("usda_foundation", "usda_sr", "usda_fndds"), sources.keys)

        val catalog = PostgresFoodCatalogRepository(database, Clock.System)
        val banana = catalog.search("banana", 5, record = false).first().food
        assertTrue(banana.name.lowercase().startsWith("banana"), banana.name)
        assertTrue(banana.per100g.kcal!! in 80.0..100.0, "banana kcal ${banana.per100g.kcal}")
        assertTrue(banana.portions.isNotEmpty())
        assertEquals(FoodTier.Reference to true, banana.tier to banana.verified, "the seed predates tiers; the trigger fills them")

        val egg = catalog.search("egg whole raw", 5, record = false).first().food
        assertTrue(egg.per100g.protein!! in 11.0..14.0, "egg protein ${egg.per100g.protein}")
        assertTrue(egg.portions.any { (it.grams ?: 0.0) in 40.0..60.0 }, "egg portions ${egg.portions}")

        val rice = catalog.search("rice white cooked", 5, record = false).map { it.food }
        assertTrue(rice.any { it.per100g.kcal!! in 120.0..140.0 }, "rice ${rice.map { it.name to it.per100g.kcal }}")

        val yogurt = catalog.search("greek yogurt plain", 5, record = false).first().food
        assertTrue(yogurt.name.contains("Greek", ignoreCase = true), yogurt.name)
        assertTrue(yogurt.per100g.protein!! > 7.0)
        assertTrue(yogurt.source != CatalogSource.OpenFoodFacts)
        assertTrue(yogurt.micros.containsKey("calcium_mg"))

        assertEquals("Egg, whole, raw", catalog.search("eggs", 5, record = false).first().food.name)
        assertEquals("Coffee, brewed", catalog.search("coffee", 5, record = false).first().food.name)

        // Categories (V16) for the Logger's Restaurant and Beverages tabs.
        val categories = database.blockingTransaction {
            FoodsTable.selectAll().mapNotNull { it[FoodsTable.category] }.groupingBy { it }.eachCount()
        }
        assertEquals(FoodCategory.entries.map { it.wire }.toSet(), categories.keys)
        assertTrue(categories.getValue(FoodCategory.Restaurant.wire) > 300, "restaurant foods $categories")
        assertTrue(categories.getValue(FoodCategory.Beverage.wire) > 500, "drinks $categories")
        val drinks = SearchFilter(category = SearchCategory.Beverage)
        assertEquals("Coffee, brewed", catalog.search("coffee", 5, record = false, filter = drinks).first().food.name)
        assertTrue(catalog.search("banana", 5, record = false, filter = drinks).none { it.food.name == "Banana, raw" })
        val restaurant = catalog.search("chicken", 10, record = false, filter = SearchFilter(category = SearchCategory.Restaurant))
        assertTrue(restaurant.isNotEmpty())

        val described = CatalogFoodDescriber(catalog).describe("2 eggs and a medium banana")
        assertEquals(listOf("Egg, whole, raw", "Banana, raw"), described.map { it.name })
        assertEquals(listOf(100.0, 118.0), described.map { it.grams })
    }
}
